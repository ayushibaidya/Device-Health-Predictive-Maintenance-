"""Regenerate wheel-only locks using the project's pinned Python container."""
import json
import pathlib
import subprocess
import sys
import tempfile
import urllib.request

root = pathlib.Path(__file__).resolve().parents[1]
if sys.version_info[:3] != (3, 13, 18):
    raise SystemExit("Run this script using the pinned Python 3.13.18 container.")
with tempfile.TemporaryDirectory() as temporary:
    for flavor in ("", "-dev"):
        report = pathlib.Path(temporary) / "report.json"
        subprocess.run([
            sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed",
            "--only-binary=:all:", "--report", str(report),
            "-r", str(root / f"processing/requirements{flavor}.in"),
        ], check=True)
        packages = json.loads(report.read_text())["install"]
        lines = ["# Generated by scripts/lock-ingestion.py using Python 3.13.18.",
                 "# All runtime and transitive dependencies are pinned; wheels are hash checked."]
        for package in sorted(packages, key=lambda item: item["metadata"]["name"].lower()):
            name, version = package["metadata"]["name"], package["metadata"]["version"]
            with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as response:
                release = json.load(response)
            hashes = sorted({item["digests"]["sha256"] for item in release["urls"]
                             if item["packagetype"] == "bdist_wheel"})
            if not hashes:
                raise SystemExit(f"No wheel hashes found for {name}")
            lines.append(f"{name}=={version} \\")
            for index, digest in enumerate(hashes):
                suffix = " \\" if index + 1 < len(hashes) else ""
                lines.append(f"    --hash=sha256:{digest}{suffix}")
        (root / f"processing/requirements{flavor}.lock").write_text("\n".join(lines) + "\n")
